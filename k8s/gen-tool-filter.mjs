// Regenerates k8s/configmap.yaml — the ENABLED_TOOLS regex the deployment reads.
//
// The pod is the ceiling for every customer on m365.mcphub.no: only mail,
// calendar, OneDrive/Files and SharePoint are reachable, whatever an
// individual tenant consents to. Per-customer trimming below this line belongs
// in Solvei's MCPServer.tool_filter, not here.
//
// Written out as an explicit tool-name alternation rather than a clever
// substring pattern, because substrings over-match: "message" would drag in the
// Teams chat surface, "file" the OneNote one. The list is derived, so it stays
// correct across upstream merges — run `make tools` after pulling upstream and
// commit the diff.
//
//   node k8s/gen-tool-filter.mjs > k8s/configmap.yaml

import { readFileSync } from 'node:fs';

const endpoints = JSON.parse(readFileSync(new URL('../src/endpoints.json', import.meta.url), 'utf8'));

// endpoints.json tags each endpoint with the presets it belongs to. These three
// map cleanly onto "email, calendar and SharePoint" — except SharePoint, which
// upstream files under the catch-all `work` preset (156 tools, including Teams
// and OneNote), so it is picked out by name instead.
const PRESETS = new Set(['mail', 'calendar', 'files']);

const names = new Set();
for (const endpoint of endpoints) {
  if ((endpoint.presets ?? []).some((preset) => PRESETS.has(preset))) {
    names.add(endpoint.toolName);
  }
}

// SharePoint sites, drives, lists and columns — but not the OneNote notebooks
// that also hang off /sites, which are a different product surface.
for (const endpoint of endpoints) {
  if (/sharepoint/.test(endpoint.toolName) && !/sharepoint-site-onenote/.test(endpoint.toolName)) {
    names.add(endpoint.toolName);
  }
}

// Utility tools live in graph-tools.ts, not endpoints.json, so they carry no
// preset tags and every filter drops them — including the downloaders that the
// drive tools' own llmTips tell the model to call.
for (const tool of ['download-bytes', 'download-bytes-to-file', 'get-download-url', 'graph-batch']) {
  names.add(tool);
}

const pattern = `^(${[...names].sort().join('|')})$`;

process.stdout.write(`# GENERATED by k8s/gen-tool-filter.mjs — do not edit by hand.
# Regenerate with \`make tools\` (after merging upstream, so new endpoints are picked up).
#
# ENABLED_TOOLS is compiled to a case-insensitive regex and matched against every
# tool name; anything that does not match is never advertised. ${names.size} tools:
# mail, calendar, OneDrive/Files and SharePoint sites/drives/lists.
apiVersion: v1
kind: ConfigMap
metadata:
  name: m365-mcp-tools
  namespace: mcphub
  labels:
    app: m365-mcp
data:
  ENABLED_TOOLS: ${JSON.stringify(pattern)}
`);
